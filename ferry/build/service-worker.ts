// Emits dist/sw.js with the exact list of built files, so the installed app opens with no signal
// (the offline shell). Nothing under /api is ever cached, and relay traffic is a WebSocket the worker
// never sees.
import type { Plugin } from 'vite'

const worker = (version: string, files: string[]) => `// generated by build/service-worker.ts
const CACHE = 'ferry-${version}'
const SHELL = ${JSON.stringify(files)}
self.addEventListener('install', (e) => {
  e.waitUntil(caches.open(CACHE).then((c) => c.addAll(SHELL)).then(() => self.skipWaiting()))
})
self.addEventListener('activate', (e) => {
  e.waitUntil(caches.keys().then((keys) => Promise.all(keys.filter((k) => k !== CACHE).map((k) => caches.delete(k)))).then(() => self.clients.claim()))
})
self.addEventListener('fetch', (e) => {
  const req = e.request
  const url = new URL(req.url)
  if (req.method !== 'GET' || url.origin !== location.origin || url.pathname.startsWith('/api/')) return
  if (req.mode === 'navigate') {
    // Network first, so an update is picked up; the cached shell when offline.
    e.respondWith(fetch(req).catch(() => caches.match('/index.html')))
    return
  }
  e.respondWith(caches.match(req).then((hit) => hit || fetch(req)))
})
`

export function serviceWorker(): Plugin {
  return {
    name: 'ferry-service-worker',
    apply: 'build',
    generateBundle(_opts, bundle) {
      const files = Object.keys(bundle).filter((f) => !f.endsWith('.map'))
      // public/ is copied beside the bundle, not part of it: list what the installed app needs.
      const pub = ['/manifest.webmanifest', '/icons/icon-192.png', '/icons/icon-512.png', '/icons/apple-touch-icon.png', '/icons/favicon.png']
      const shell = ['/', '/index.html', ...pub, ...files.map((f) => `/${f}`)]
      const version = Date.now().toString(36)
      this.emitFile({ type: 'asset', fileName: 'sw.js', source: worker(version, [...new Set(shell)]) })
    }
  }
}
